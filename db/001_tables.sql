
CREATE TABLE categoria (
	codigo INTEGER  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	nombre VARCHAR(255) NOT NULL,
	categoria_id INTEGER,
	FOREIGN KEY (categoria_id) REFERENCES categoria (codigo)
		ON UPDATE CASCADE
		ON DELETE SET NULL
);


CREATE TABLE producto (
	codigo INTEGER  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	nombre VARCHAR(255) NOT NULL,
	precio NUMERIC(12,2) NOT NULL CONSTRAINT product_price_format CHECK (precio > 0),
	marca VARCHAR(128),
	talla VARCHAR(64),
	color VARCHAR(64),
	material VARCHAR(128),
	categoria_id INTEGER,
	fotos TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
	stock INTEGER NOT NULL DEFAULT 0 CONSTRAINT stock_format CHECK (stock >= 0),
	FOREIGN KEY (categoria_id) REFERENCES categoria (codigo)
		ON UPDATE CASCADE
		ON DELETE SET NULL
);


CREATE TABLE persona (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	email VARCHAR(255) UNIQUE NOT NULL CONSTRAINT persona_email_check CHECK (email ~ '^[A-Za-z0-9_.]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$'),
	password TEXT NOT NULL,
	nombre VARCHAR(255),
	telefono VARCHAR(8) UNIQUE CONSTRAINT persona_telefono_check CHECK (telefono ~ '^[0-9]{8}$'),
	foto TEXT,
	create_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);


CREATE TYPE CLIENTE_STATUS AS ENUM ('activo', 'deshabilitado', 'eliminado');
CREATE TABLE cliente (
	id INTEGER PRIMARY KEY,
	estado CLIENTE_STATUS NOT NULL DEFAULT 'activo',
	create_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
	FOREIGN KEY (id) REFERENCES persona (id)
		ON UPDATE CASCADE
		ON DELETE CASCADE
);


CREATE TABLE venta (
	numero INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	monto NUMERIC(12,2) NOT NULL DEFAULT 0 CONSTRAINT monto_format CHECK (monto >= 0),
	fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
	cliente_id INTEGER NOT NULL,
	FOREIGN KEY (cliente_id) REFERENCES cliente (id)
		ON UPDATE CASCADE
		ON DELETE SET NULL
);


CREATE TABLE tienda (
	codigo SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	latitud_ubicacion NUMERIC(12,9) NOT NULL,
	longitud_ubicacion NUMERIC(12,9) NOT NULL
);


CREATE TABLE item (
	sku BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	fecha_entrega TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
	producto_id INTEGER NOT NULL,
	venta_id INTEGER,
	tienda_id SMALLINT NOT NULL,
	FOREIGN KEY (producto_id) REFERENCES producto (codigo)
		ON UPDATE CASCADE
		ON DELETE CASCADE,
	FOREIGN KEY (venta_id) REFERENCES venta (numero)
		ON UPDATE CASCADE
		ON DELETE SET NULL,
	FOREIGN KEY (tienda_id) REFERENCES tienda (codigo)
		ON UPDATE CASCADE
		ON DELETE CASCADE
);


CREATE TYPE ENVIO_STAGE AS ENUM ('pendiente', 'enviado', 'recivido');
CREATE TABLE envio (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	latitud_destino NUMERIC(12,9) NOT NULL,
	longitud_destino NUMERIC(12,9) NOT NULL,
	estado ENVIO_STAGE NOT NULL DEFAULT 'pendiente',
	fecha_envio TIMESTAMP,
	fecha_entrega TIMESTAMP
);


CREATE TYPE EMPLEADO_ROLE AS ENUM ('admin', 'cajero', 'viewer');
CREATE TABLE empleado (
	id INTEGER NOT NULL,
	role EMPLEADO_ROLE NOT NULL DEFAULT 'cajero',
	tienda_id SMALLINT,
	create_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
	FOREIGN KEY (id) REFERENCES persona (id)
		ON UPDATE CASCADE
		ON DELETE CASCADE,
	FOREIGN KEY (tienda_id) REFERENCES tienda (codigo)
		ON UPDATE CASCADE
		ON DELETE SET NULL
);













